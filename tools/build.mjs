#!/usr/bin/env node
// Copies validated content into data/ and regenerates sw.js with a precache list + content hash.
// Usage: node tools/build.mjs     (run from the repo root)
import fs from 'node:fs';
import path from 'node:path';
import crypto from 'node:crypto';
import { execFileSync } from 'node:child_process';

const content = fs.readdirSync('content').filter((f) => f.endsWith('.json'));
if (content.length) {
  execFileSync('node', ['tools/validate.mjs', ...content.map((f) => path.join('content', f))], { stdio: 'inherit' });
  for (const f of content) {
    const d = JSON.parse(fs.readFileSync(path.join('content', f), 'utf8'));
    fs.writeFileSync(path.join('data', f), JSON.stringify(d));
  }
}

const walk = (dir) => fs.readdirSync(dir, { withFileTypes: true }).flatMap((e) => {
  const p = path.join(dir, e.name);
  return e.isDirectory() ? walk(p) : [p];
});
const files = ['index.html', 'manifest.webmanifest', ...['css', 'js', 'data', 'icons'].flatMap(walk)]
  .filter((f) => !path.basename(f).startsWith('.'))
  .sort();
const hash = crypto.createHash('sha256');
for (const f of files) hash.update(f).update(fs.readFileSync(f));
const version = hash.digest('hex').slice(0, 12);

const sw = `// Generated by tools/build.mjs — do not edit by hand.
const VERSION = '${version}';
const CACHE = 'michi-' + VERSION;
const FILES = ${JSON.stringify(['./', ...files], null, 1)};

self.addEventListener('install', (e) => {
  e.waitUntil(caches.open(CACHE).then((c) => c.addAll(FILES)).then(() => self.skipWaiting()));
});

self.addEventListener('activate', (e) => {
  e.waitUntil(
    caches.keys()
      .then((keys) => Promise.all(keys.filter((k) => k.startsWith('michi-') && k !== CACHE).map((k) => caches.delete(k))))
      .then(() => self.clients.claim()),
  );
});

// Cache-first: the whole app is precached, so it works fully offline.
self.addEventListener('fetch', (e) => {
  if (e.request.method !== 'GET' || new URL(e.request.url).origin !== location.origin) return;
  e.respondWith(
    caches.match(e.request, { ignoreSearch: true }).then((hit) => hit || fetch(e.request).catch(() => caches.match('./'))),
  );
});
`;
fs.writeFileSync('sw.js', sw);
const bytes = files.reduce((a, f) => a + fs.statSync(f).size, 0);
console.log(`sw.js: ${files.length} files, ${(bytes / 1e6).toFixed(2)} MB, version ${version}`);
